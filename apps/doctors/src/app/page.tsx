"use client"

import { StartCallButton } from '@/components/calls/StartCallButton'
import { DEMO_PATIENT_ID } from '@/data/demoData'
import { useDoctorsPortal } from '@/components/layout/DoctorsPortalShell'
import { PrescriptionModal } from '@/components/medical/PrescriptionModal'
import { QuickNotesModal } from '@/components/medical/QuickNotesModal'
import { TelemedicineSignalingPanel } from '@/components/telemedicine/TelemedicineSignalingPanel'
import { useActiveSession, usePatientData } from '@/hooks'
import { useAuthenticatedUser } from '@/hooks/useAuthenticatedUser'
import { useMedicalHistoryStore } from '@/stores/medicalHistoryStore'
import { getPatientDisplayName } from '@/utils/patientDisplay'
import { logger } from '@autamedica/shared'
import { UnifiedVideoCall } from '@autamedica/telemedicine'
import {
  Activity,
  Brain,
  CheckCircle2,
  ChevronDown,
  ChevronUp,
  FileText,
  Loader2,
  MonitorUp,
  Phone,
  Pill,
  Sparkles,
  X,
} from 'lucide-react'
import type { JSX } from 'react'
import { useEffect, useMemo, useState } from 'react'

export default function DoctorsHomePage(): JSX.Element {
  const { user } = useAuthenticatedUser()
  const { session } = useActiveSession()
  const { patient } = usePatientData(session?.patientId ?? null)

  const { addEntry } = useMedicalHistoryStore()
  const { isFocusMode, setFocusMode } = useDoctorsPortal()

  useEffect(() => {
    return () => setFocusMode(false)
  }, [setFocusMode])

  const [showDiagnosisPanel, setShowDiagnosisPanel] = useState(false)
  const [showTelemedicinePanel, setShowTelemedicinePanel] = useState(false)
  const [isQuickActionsVisible, setIsQuickActionsVisible] = useState(false)
  const [aiProcessing, setAiProcessing] = useState(false)
  const [showNotesModal, setShowNotesModal] = useState(false)
  const [showPrescriptionModal, setShowPrescriptionModal] = useState(false)
  const [isQuickActionsCollapsed, setIsQuickActionsCollapsed] = useState(false)

  const signalingRoomId = useMemo(() => session?.sessionId ?? 'guest-room', [session?.sessionId])
  const signalingUserId = useMemo(() => {
    if (typeof window === 'undefined' || typeof crypto === 'undefined') {
      return 'dr-invitado'
    }
    const storageKey = 'autamedica-doctor-signaling-id'
    const cached = window.sessionStorage.getItem(storageKey)
    if (cached) {
      return cached
    }
    const generated = crypto.randomUUID()
    window.sessionStorage.setItem(storageKey, generated)
    return generated
  }, [])

  useEffect(() => {
    if (!isFocusMode) {
      setIsQuickActionsVisible(false)
      setIsQuickActionsCollapsed(false)
    }
  }, [isFocusMode])

  const doctorName = useMemo(() => {
    if (user?.profile) {
      const name = [user.profile.first_name, user.profile.last_name].filter(Boolean).join(' ').trim()
      return name || user.email
    }
    return 'Doctor de prueba'
  }, [user])

  const handleCallStart = () => {
    setFocusMode(true)
    setIsQuickActionsCollapsed(true)
  }

  const handleCallEnd = () => {
    setFocusMode(false)
  }

  const handleStatusChange = (_status: string) => {
    logger.info('[DoctorsHomePage] call status:', _status)
  }

  async function handleAnalyzeWithAI() {
    setAiProcessing(true)
    setShowDiagnosisPanel(true)

    await new Promise(resolve => setTimeout(resolve, 2000))

    await addEntry({
      type: 'analysis',
      content: 'Análisis IA completado: Posible faringitis aguda',
      metadata: {
        aiAnalysis: {
          suggestions: ['Antibióticos recomendados', 'Reposo 48h'],
          riskFactors: ['Fiebre elevada'],
          confidence: 0.85
        }
      },
      doctorId: user?.id || 'current-doctor',
      patientId: session?.patientId || 'guest-patient',
      autoGenerated: true
    })

    setAiProcessing(false)
  }

  const toggleQuickActionsVisibility = () => {
    setIsQuickActionsVisible((prev) => {
      const next = !prev
      if (next) {
        setIsQuickActionsCollapsed(false)
      }
      return next
    })
  }

  const closeQuickActions = () => {
    setIsQuickActionsVisible(false)
  }

  const hasRealPatient = user && session?.patientId && session.patientId !== DEMO_PATIENT_ID

  return (
    <div className="flex min-h-0 flex-1 flex-col text-slate-900">
      <div className={`call-area ${isFocusMode ? 'gap-3' : 'gap-4'} flex min-h-0 flex-1 flex-col lg:flex-row`}>
        <section className="call-area__videoCard relative flex min-h-0 flex-1 flex-col">
          <div className="relative flex min-h-0 flex-1 overflow-hidden rounded-lg">
            <UnifiedVideoCall
              roomId={signalingRoomId}
              userId={user?.id ?? signalingUserId}
              userType="doctor"
              userName={doctorName}
              theme="doctor"
              onCallStart={handleCallStart}
              onCallEnd={handleCallEnd}
              onStatusChange={handleStatusChange}
              className="h-full w-full"
            />
          </div>

          {showTelemedicinePanel && (
            <TelemedicineSignalingPanel
              roomId={signalingRoomId}
              userId={signalingUserId}
              userType="doctor"
              metadata={{
                patientId: session?.patientId ?? 'guest-patient',
                patientName: getPatientDisplayName(patient),
              }}
              className="mt-3 rounded-2xl border border-slate-200 bg-white p-4 shadow-lg sm:p-6"
            />
          )}
        </section>

        {isFocusMode && (
          <button
            type="button"
            onClick={toggleQuickActionsVisibility}
            className={`call-area__quickActionsHandle hidden flex-col items-center gap-1 rounded-2xl border border-slate-200 bg-white/90 px-3 py-3 text-xs font-medium text-slate-600 shadow-lg transition hover:border-violet-300 hover:text-violet-700 lg:flex ${
              isQuickActionsVisible ? 'ring-1 ring-violet-400/60' : ''
            }`}
            aria-expanded={isQuickActionsVisible}
            aria-label="Herramientas rápidas de la consulta"
          >
            {isQuickActionsVisible ? (
              <>
                <X className="h-4 w-4" />
                <span className="text-[11px] font-semibold uppercase tracking-wide">Cerrar panel</span>
              </>
            ) : (
              <>
                <span className="flex items-center gap-1 text-violet-500">
                  <FileText className="h-3 w-3" />
                  <Pill className="h-3 w-3" />
                  <Activity className="h-3 w-3" />
                  <MonitorUp className="h-3 w-3" />
                  <Brain className="h-3 w-3" />
                </span>
                <span className="text-[11px] font-semibold uppercase tracking-wide">Herramientas</span>
                <span className="text-[10px] font-normal text-slate-500">Notas · Rx · Signos · IA</span>
              </>
            )}
          </button>
        )}

        <aside
          className={`right-drawer hidden h-full flex-col space-y-4 rounded-3xl border border-slate-200 bg-white p-4 shadow-lg lg:flex ${
            isFocusMode && isQuickActionsVisible ? 'right-drawer--open' : ''
          }`}
        >
          <div className="flex items-center justify-between px-1 pb-0">
            <h3 className="text-xs font-semibold uppercase tracking-[0.25em] text-slate-500">Acciones rápidas</h3>
            <div className="flex items-center gap-1">
              {isFocusMode && (
                <button
                  type="button"
                  onClick={closeQuickActions}
                  className="rounded-lg p-1 text-slate-400 transition hover:bg-slate-100 hover:text-slate-700"
                  aria-label="Cerrar acciones rápidas"
                >
                  <X className="h-4 w-4" />
                </button>
              )}
              <button
                type="button"
                onClick={() => setIsQuickActionsCollapsed(!isQuickActionsCollapsed)}
                className="rounded-lg p-1 text-slate-400 transition hover:bg-slate-100 hover:text-slate-700"
                aria-expanded={!isQuickActionsCollapsed}
                aria-controls="quick-actions-panel"
              >
                {isQuickActionsCollapsed ? <ChevronDown className="h-4 w-4" /> : <ChevronUp className="h-4 w-4" />}
              </button>
            </div>
          </div>

          {!isQuickActionsCollapsed && (
            <div id="quick-actions-panel" className="space-y-3 px-1 pb-2">
              <div className="grid gap-2 sm:grid-cols-2 lg:grid-cols-1">
                {hasRealPatient && session.patientId && (
                  <StartCallButton
                    doctorId={user.id}
                    patientId={session.patientId}
                    patientName={getPatientDisplayName(patient)}
                    className="flex w-full items-center gap-2 rounded-lg border border-violet-200 bg-violet-50 px-3 py-2 text-xs font-medium text-violet-700 transition hover:bg-violet-100"
                  />
                )}
                <CompactAction
                  label="Notas"
                  icon={<FileText className="h-4 w-4" />}
                  onClick={() => setShowNotesModal(true)}
                />
                <CompactAction
                  label="Prescribir"
                  icon={<Pill className="h-4 w-4" />}
                  onClick={() => setShowPrescriptionModal(true)}
                />
                <CompactAction
                  label="Signos vitales"
                  icon={<Activity className="h-4 w-4" />}
                />
                <CompactAction
                  label={showTelemedicinePanel ? 'Ocultar telemedicina' : 'Telemedicina'}
                  icon={<MonitorUp className="h-4 w-4" />}
                  intent={showTelemedicinePanel ? 'primary' : 'default'}
                  onClick={() => setShowTelemedicinePanel(!showTelemedicinePanel)}
                />
                <CompactAction
                  label={aiProcessing ? 'Procesando...' : 'Análisis IA'}
                  icon={<Brain className="h-4 w-4" />}
                  intent="success"
                  onClick={handleAnalyzeWithAI}
                />
              </div>

              <div className="rounded-lg border border-emerald-200 bg-emerald-50 p-2">
                <div className="flex items-center gap-2">
                  <Sparkles className="h-3 w-3 text-emerald-500" />
                  <p className="text-xs text-emerald-700">Sincronización automática</p>
                </div>
              </div>
            </div>
          )}

          {isQuickActionsCollapsed && (
            <div className="px-1 pb-2">
              <div className="flex items-center justify-center gap-3 rounded-lg border border-slate-200 bg-slate-50 py-2">
                <FileText className="h-3 w-3 text-slate-400" />
                <Pill className="h-3 w-3 text-slate-400" />
                <Activity className="h-3 w-3 text-slate-400" />
                <Brain className="h-3 w-3 text-slate-400" />
                <span className="text-xs text-slate-400">{hasRealPatient ? '6' : '5'} acciones disponibles</span>
              </div>
            </div>
          )}
        </aside>
      </div>

      {isFocusMode && (
        <div className="mt-3 flex items-center justify-center lg:hidden">
          <button
            type="button"
            onClick={() => setIsQuickActionsCollapsed(false)}
            className="flex items-center gap-2 rounded-full border border-slate-200 bg-white/90 px-4 py-2 text-xs text-slate-600 transition hover:border-slate-300 hover:text-slate-900"
          >
            <MonitorUp className="h-4 w-4" />
            Acciones rápidas
          </button>
        </div>
      )}

      {isFocusMode && (
        <div className="fixed bottom-6 right-6 z-20 flex items-center gap-3 lg:hidden">
          <button
            type="button"
            onClick={() => setIsQuickActionsCollapsed(false)}
            className="flex items-center gap-2 rounded-full bg-violet-600 px-4 py-2 text-xs font-semibold text-white shadow-lg transition hover:bg-violet-500"
          >
            <Sparkles className="h-4 w-4" />
            Acciones
          </button>
        </div>
      )}

      {showDiagnosisPanel && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/40 px-4 backdrop-blur-sm">
          <div className="w-full max-w-3xl rounded-2xl border border-slate-200 bg-white p-5 shadow-xl sm:p-6">
            <header className="mb-6 flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
              <div className="flex items-center gap-3 text-slate-900">
                <div className="flex h-10 w-10 items-center justify-center rounded-full bg-violet-100 text-violet-600">
                  <Brain className="h-5 w-5" />
                </div>
                <div>
                  <h2 className="text-lg font-semibold">Analisis IA · {getPatientDisplayName(patient)}</h2>
                  <p className="text-xs text-slate-500">Carga un resumen de sintomas para generar diagnosticos asistidos.</p>
                </div>
              </div>
              <button
                type="button"
                onClick={() => setShowDiagnosisPanel(false)}
                className="self-start rounded-full border border-slate-200 px-3 py-1 text-xs text-slate-600 transition hover:bg-slate-50 hover:text-slate-900 focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-violet-500 sm:self-auto"
              >
                Cerrar
              </button>
            </header>

            <div className="grid gap-4 sm:grid-cols-2">
              <label className="space-y-2 text-sm text-slate-700">
                <span>Sintomas principales</span>
                <textarea
                  defaultValue="Dolor de garganta severo, fiebre de 38.5C, dificultad para tragar"
                  className="min-h-[120px] w-full rounded-xl border border-slate-300 bg-white p-3 text-sm text-slate-900 placeholder:text-slate-400 focus:border-violet-500 focus:outline-none focus:ring-2 focus:ring-violet-500/40"
                />
              </label>
              <label className="space-y-2 text-sm text-slate-700">
                <span>Duracion de sintomas</span>
                <input
                  defaultValue="2 dias"
                  className="w-full rounded-xl border border-slate-300 bg-white p-3 text-sm text-slate-900 placeholder:text-slate-400 focus:border-violet-500 focus:outline-none focus:ring-2 focus:ring-violet-500/40"
                />
              </label>
            </div>

            {aiProcessing && (
              <div className="mt-6 flex items-center gap-3 rounded-lg border border-violet-200 bg-violet-50 p-4">
                <Loader2 className="h-5 w-5 animate-spin text-violet-600" />
                <p className="text-sm text-violet-700">Analizando sintomas con IA...</p>
              </div>
            )}

            <div className="mt-6 flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
              <div className="flex items-center gap-2 text-xs text-slate-500">
                <CheckCircle2 className="h-4 w-4 text-emerald-500" />
                Datos encriptados y auditados.
              </div>
              <button
                type="button"
                disabled={aiProcessing}
                className="flex items-center gap-2 self-stretch rounded-xl bg-violet-600 px-5 py-2 text-sm font-semibold text-white transition hover:bg-violet-700 disabled:opacity-50 sm:self-auto"
              >
                <Brain className="h-4 w-4" />
                {aiProcessing ? 'Analizando...' : 'Analizar con IA'}
              </button>
            </div>
          </div>
        </div>
      )}

      {showNotesModal && (
        <QuickNotesModal
          patientName={getPatientDisplayName(patient)}
          patientId={session?.patientId || 'guest-patient'}
          onClose={() => setShowNotesModal(false)}
        />
      )}

      {showPrescriptionModal && (
        <PrescriptionModal
          patientName={getPatientDisplayName(patient)}
          patientId={session?.patientId || 'guest-patient'}
          onClose={() => setShowPrescriptionModal(false)}
        />
      )}

      {isFocusMode && isQuickActionsVisible && (
        <button
          type="button"
          className="call-area__drawerScrim fixed inset-0 z-30 hidden bg-slate-900/40 backdrop-blur-sm lg:block"
          aria-label="Cerrar acciones rápidas"
          onClick={closeQuickActions}
        />
      )}
    </div>
  )
}

interface CompactActionProps {
  label: string
  icon: JSX.Element
  intent?: 'default' | 'primary' | 'success'
  onClick?: () => void
}

function CompactAction({ label, icon, intent = 'default', onClick }: CompactActionProps): JSX.Element {
  const intentStyles = {
    default: 'border-slate-200 bg-white text-slate-600 hover:bg-slate-50',
    primary: 'border-violet-200 bg-violet-50 text-violet-700 hover:bg-violet-100',
    success: 'border-emerald-200 bg-emerald-50 text-emerald-700 hover:bg-emerald-100',
  }

  return (
    <button
      type="button"
      onClick={onClick}
      className={`flex w-full items-center gap-2 rounded-lg border px-3 py-2 text-xs font-medium transition ${intentStyles[intent]}`}
    >
      <span className={intent === 'success' ? 'text-emerald-500' : intent === 'primary' ? 'text-violet-500' : 'text-slate-400'}>
        {icon}
      </span>
      {label}
    </button>
  )
}
